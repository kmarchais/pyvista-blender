"""Translate glyph specifications into Geometry-Nodes-instanced bpy objects.

PyVista's ``mesh.glyph(...)`` returns a *baked* PolyData — every glyph
copy is materialised as actual geometry, then merged. For ``N`` points
and a ``V``-vertex glyph mesh that's ``N * V`` vertices to push through
Cycles. The bridge avoids that by hosting one copy of the glyph mesh
and using Blender's :class:`GeometryNodeInstanceOnPoints` to generate
the instances at render time: one ``V``-vertex geom data block + one
``N``-vertex points data block + one node group.

Per-point ``orient`` (3D vector field) is read via a
``GeometryNodeInputNamedAttribute`` and fed through
``FunctionNodeAlignRotationToVector`` to produce the instance rotation.
Per-point ``scale`` (scalar field) is multiplied by the global
``factor`` and fed into the ``Scale`` socket directly. Either or both
can be omitted — defaults to identity rotation / unit scale.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import bpy
import numpy as np

from pyvista_blender._glyph import GlyphSpec

if TYPE_CHECKING:
    import pyvista as pv

__all__ = [
    "GlyphSpec",
    "build_glyph_channel_image",
    "inject_glyph_channel_override",
    "translate_glyph",
]


def translate_glyph(spec: GlyphSpec, ordinal: int) -> bpy.types.Object:
    """Materialise one :class:`GlyphSpec` as an instancing bpy object.

    The returned object carries:

    * A vertex-only bpy mesh holding the source dataset's points, plus
      ``orient`` / ``scale`` attributes copied over if the spec asks for
      them.
    * A ``NODES`` modifier driving a fresh :class:`GeometryNodeTree`
      that instances ``spec.geom`` at every vertex with the requested
      rotation + scale.

    The glyph geom is hidden from camera rays so the original mesh
    doesn't appear at the origin alongside the instances.

    Parameters
    ----------
    spec
        Source dataset + glyph shape + field names.
    ordinal
        Disambiguator for the bpy data block names so multiple
        ``add_glyph(...)`` calls don't collide.

    Returns
    -------
    bpy.types.Object
        The instancing parent object, linked into the active scene.

    """
    name = spec.name or f"PVGlyph_{ordinal}"
    geom_obj = _build_geom_object(spec.geom, name)
    points_obj = _build_points_object(spec, name)
    _attach_instancer_modifier(points_obj, geom_obj, spec, name)
    return points_obj


def _build_geom_object(geom: pv.DataSet, base_name: str) -> bpy.types.Object:
    """Materialise the glyph shape as a hidden bpy mesh+object.

    Returns
    -------
    bpy.types.Object
        Hidden from camera rays (``hide_render = True``) — only the
        instances generated by the GN modifier should appear.

    """
    surface = geom.extract_surface(algorithm="dataset_surface").triangulate()
    verts = np.ascontiguousarray(surface.points, dtype=np.float32)
    tris = np.ascontiguousarray(surface.regular_faces, dtype=np.int32)

    mesh_data = bpy.data.meshes.new(f"{base_name}_geom")
    mesh_data.vertices.add(len(verts))
    mesh_data.vertices.foreach_set("co", verts.ravel())
    mesh_data.loops.add(len(tris) * 3)
    mesh_data.loops.foreach_set("vertex_index", tris.ravel())
    mesh_data.polygons.add(len(tris))
    mesh_data.polygons.foreach_set(
        "loop_start", np.arange(len(tris), dtype=np.int32) * 3
    )
    mesh_data.polygons.foreach_set("loop_total", np.full(len(tris), 3, dtype=np.int32))
    mesh_data.update(calc_edges=True)
    mesh_data.validate()

    obj = bpy.data.objects.new(f"{base_name}_geom", mesh_data)
    obj.hide_render = True
    bpy.context.scene.collection.objects.link(obj)
    return obj


def _build_points_object(spec: GlyphSpec, base_name: str) -> bpy.types.Object:
    """Materialise the source points as a vertex-only bpy mesh.

    Per-point orient (vector) and scale (scalar) fields are written to
    POINT-domain attributes so the GN node group can read them by name.

    Returns
    -------
    bpy.types.Object
        Object wrapping the freshly-allocated vertex-only mesh.

    """
    points = np.ascontiguousarray(spec.source.points, dtype=np.float32)
    mesh_data = bpy.data.meshes.new(f"{base_name}_points")
    mesh_data.vertices.add(len(points))
    mesh_data.vertices.foreach_set("co", points.ravel())
    mesh_data.update()

    if spec.orient and spec.orient in spec.source.point_data:
        vectors = np.ascontiguousarray(
            spec.source.point_data[spec.orient], dtype=np.float32
        )
        attr = mesh_data.attributes.new(
            name="pv_orient", type="FLOAT_VECTOR", domain="POINT"
        )
        attr.data.foreach_set("vector", vectors.ravel())

    if spec.scale and spec.scale in spec.source.point_data:
        scalars = np.ascontiguousarray(
            spec.source.point_data[spec.scale], dtype=np.float32
        )
        attr = mesh_data.attributes.new(name="pv_scale", type="FLOAT", domain="POINT")
        attr.data.foreach_set("value", scalars.ravel())

    obj = bpy.data.objects.new(f"{base_name}_points", mesh_data)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def _attach_instancer_modifier(
    points_obj: bpy.types.Object,
    geom_obj: bpy.types.Object,
    spec: GlyphSpec,
    base_name: str,
) -> None:
    """Build the GN node group + modifier that drives the instancing."""
    tree = bpy.data.node_groups.new(f"{base_name}_GN", "GeometryNodeTree")
    interface = tree.interface
    interface.new_socket("Geometry", in_out="INPUT", socket_type="NodeSocketGeometry")
    interface.new_socket("Geometry", in_out="OUTPUT", socket_type="NodeSocketGeometry")

    group_input = tree.nodes.new("NodeGroupInput")
    group_input.location = (-600, 0)
    group_output = tree.nodes.new("NodeGroupOutput")
    group_output.location = (600, 0)

    object_info = tree.nodes.new("GeometryNodeObjectInfo")
    object_info.location = (-400, -200)
    object_info.inputs["Object"].default_value = geom_obj
    object_info.inputs["As Instance"].default_value = True

    instancer = tree.nodes.new("GeometryNodeInstanceOnPoints")
    instancer.location = (0, 0)
    tree.links.new(group_input.outputs["Geometry"], instancer.inputs["Points"])
    tree.links.new(object_info.outputs["Geometry"], instancer.inputs["Instance"])

    if spec.orient:
        rotation_socket = _build_orient_chain(tree)
        tree.links.new(rotation_socket, instancer.inputs["Rotation"])

    scale_socket = _build_scale_chain(tree, spec)
    tree.links.new(scale_socket, instancer.inputs["Scale"])

    tree.links.new(instancer.outputs["Instances"], group_output.inputs["Geometry"])

    modifier = points_obj.modifiers.new(name="PVGlyph", type="NODES")
    modifier.node_group = tree


def _build_orient_chain(tree: bpy.types.NodeTree) -> bpy.types.NodeSocket:
    """Read ``pv_orient`` and align the instance's +Z axis to that vector.

    Returns
    -------
    bpy.types.NodeSocket
        The terminal ``Rotation`` socket to plug into the instancer.

    """
    named_attr = tree.nodes.new("GeometryNodeInputNamedAttribute")
    named_attr.location = (-400, 100)
    named_attr.data_type = "FLOAT_VECTOR"
    named_attr.inputs["Name"].default_value = "pv_orient"

    align = tree.nodes.new("FunctionNodeAlignRotationToVector")
    align.location = (-200, 100)
    tree.links.new(named_attr.outputs["Attribute"], align.inputs["Vector"])
    return align.outputs["Rotation"]


def _build_scale_chain(
    tree: bpy.types.NodeTree, spec: GlyphSpec
) -> bpy.types.NodeSocket:
    """Compute per-point scale = ``factor * pv_scale``.

    When ``spec.scale`` is ``None`` the chain collapses to a constant
    vector ``(factor, factor, factor)`` so every glyph gets the same
    uniform size.

    Returns
    -------
    bpy.types.NodeSocket
        The terminal Vector output to plug into the instancer's Scale.

    """
    factor = float(spec.factor)
    combine = tree.nodes.new("ShaderNodeCombineXYZ")
    combine.location = (-200, -100)

    if spec.scale:
        named = tree.nodes.new("GeometryNodeInputNamedAttribute")
        named.location = (-600, -100)
        named.data_type = "FLOAT"
        named.inputs["Name"].default_value = "pv_scale"

        multiply = tree.nodes.new("ShaderNodeMath")
        multiply.location = (-400, -100)
        multiply.operation = "MULTIPLY"
        multiply.inputs[1].default_value = factor
        tree.links.new(named.outputs["Attribute"], multiply.inputs[0])

        for axis in ("X", "Y", "Z"):
            tree.links.new(multiply.outputs["Value"], combine.inputs[axis])
    else:
        for axis in ("X", "Y", "Z"):
            combine.inputs[axis].default_value = factor

    return combine.outputs["Vector"]


