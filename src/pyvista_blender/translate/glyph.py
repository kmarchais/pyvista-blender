def build_glyph_channel_image(
    channel_name: str,
    frames: list[tuple[int, np.ndarray]],
    *,
    base_name: str,
) -> bpy.types.Image:
    """Pack per-frame channel data as a float RGBA bpy image.

    Layout: rows = frames (frame 0 at the bottom row, matching bpy's
    bottom-up pixel order), columns = point indices, channels = RGBA.
    Vector channels write into RGB with alpha=1; scalar channels write
    ``(value, 0, 0, 1)`` so the same image format handles both.

    Parameters
    ----------
    channel_name
        ``"positions"`` / ``"orient"`` / ``"scale"``. Anything other
        than ``"scale"`` writes into RGB; ``"scale"`` writes into R only.
    frames
        Per-frame ``(frame_index, values)`` pairs. ``values`` is
        ``(N_points, 3)`` for vector channels, ``(N_points,)`` for
        scalar. All frames must have the same N_points.
    base_name
        Name prefix for the image data-block (typically the bpy
        points object's name).

    Returns
    -------
    bpy.types.Image
        Float-buffer image already loaded into ``bpy.data.images`` and
        packed via :meth:`bpy.types.Image.pack` so it embeds inside
        the .blend on save.

    """
    n_frames = len(frames)
    n_points = frames[0][1].shape[0]
    image_name = f"{base_name}__{channel_name}.exr"

    existing = bpy.data.images.get(image_name)
    if existing is not None:
        bpy.data.images.remove(existing)

    image = bpy.data.images.new(
        image_name, width=n_points, height=n_frames, alpha=True, float_buffer=True
    )

    pixels = np.zeros((n_frames, n_points, 4), dtype=np.float32)
    pixels[..., 3] = 1.0
    for row, (_frame_index, values) in enumerate(frames):
        if channel_name in {"positions", "orient"}:
            pixels[row, :, :3] = values
        else:
            pixels[row, :, 0] = values

    image.pixels.foreach_set(pixels.ravel())
    image.update()
    image.pack()
    return image


def inject_glyph_channel_override(
    tree: bpy.types.NodeTree,
    channel_name: str,
    image: bpy.types.Image,
    *,
    n_frames: int,
    frame_start: int,
) -> None:
    """Splice a per-frame override sub-graph upstream of the glyph instancer.

    The sub-graph samples ``image`` at
    ``((point_index + 0.5) / n_points, (frame - frame_start + 0.5) / n_frames)``
    and either pipes the result into a ``Set Position`` node (positions
    channel) or a ``Store Named Attribute`` node (``pv_orient`` /
    ``pv_scale``). The stored attribute is read by the existing
    ``Input Named Attribute`` nodes downstream, so the instancer
    consumes the per-frame value without further wiring changes.
    """
    instancer = _find_node(tree, "GeometryNodeInstanceOnPoints")
    group_input = _find_node(tree, "NodeGroupInput")
    if instancer is None or group_input is None:
        return

    sampler_socket = _build_glyph_image_sampler(
        tree, image, n_frames=n_frames, frame_start=frame_start
    )
    upstream_socket = _current_geometry_source_into(
        tree, instancer.inputs["Points"], fallback=group_input.outputs["Geometry"]
    )

    if channel_name == "positions":
        set_pos = tree.nodes.new("GeometryNodeSetPosition")
        set_pos.location = (-300, 200)
        tree.links.new(upstream_socket, set_pos.inputs["Geometry"])
        tree.links.new(sampler_socket, set_pos.inputs["Position"])
        _relink(tree, instancer.inputs["Points"], set_pos.outputs["Geometry"])
        return

    store = tree.nodes.new("GeometryNodeStoreNamedAttribute")
    store.location = (-300, 200)
    store.domain = "POINT"
    if channel_name == "orient":
        store.data_type = "FLOAT_VECTOR"
        store.inputs["Name"].default_value = "pv_orient"
        tree.links.new(sampler_socket, store.inputs["Value"])
    else:
        store.data_type = "FLOAT"
        store.inputs["Name"].default_value = "pv_scale"
        sep = tree.nodes.new("ShaderNodeSeparateXYZ")
        sep.location = (-450, 100)
        tree.links.new(sampler_socket, sep.inputs[0])
        tree.links.new(sep.outputs["X"], store.inputs["Value"])
    tree.links.new(upstream_socket, store.inputs["Geometry"])
    _relink(tree, instancer.inputs["Points"], store.outputs["Geometry"])


def _find_node(tree: bpy.types.NodeTree, bl_idname: str) -> bpy.types.Node | None:
    """Return the first node in ``tree`` matching ``bl_idname`` (or ``None``).

    Returns
    -------
    bpy.types.Node or None
        First matching node, or ``None`` when the tree carries none of
        that type (defensive: a tree not built by ``translate_glyph``).

    """
    for node in tree.nodes:
        if node.bl_idname == bl_idname:
            return node
    return None


def _current_geometry_source_into(
    tree: bpy.types.NodeTree,
    target: bpy.types.NodeSocket,
    *,
    fallback: bpy.types.NodeSocket,
) -> bpy.types.NodeSocket:
    """Return the socket currently feeding ``target``, or ``fallback``.

    Returns
    -------
    bpy.types.NodeSocket
        The existing upstream socket on the first link into ``target``,
        or ``fallback`` when no such link exists.

    """
    for link in tree.links:
        if link.to_socket is target:
            return link.from_socket
    return fallback


def _relink(
    tree: bpy.types.NodeTree,
    to_socket: bpy.types.NodeSocket,
    new_from_socket: bpy.types.NodeSocket,
) -> None:
    """Drop any existing link into ``to_socket`` and connect ``new_from_socket``."""
    for link in list(tree.links):
        if link.to_socket is to_socket:
            tree.links.remove(link)
    tree.links.new(new_from_socket, to_socket)


def _build_glyph_image_sampler(
    tree: bpy.types.NodeTree,
    image: bpy.types.Image,
    *,
    n_frames: int,
    frame_start: int,
) -> bpy.types.NodeSocket:
    """Wire a per-frame, per-point GN sampler over ``image``.

    The sampler reads the current vertex index, normalises to atlas U;
    pulls scene time from the Scene Time node, offsets by
    ``frame_start``, normalises to atlas V; combines into a 2D vector;
    feeds an Image Texture node whose ``Image`` input is bound to the
    pre-built ``image``.

    Returns
    -------
    bpy.types.NodeSocket
        The Image Texture's ``Color`` output socket, ready for the
        caller's Set-Position or Store-Named-Attribute sink.

    """
    index = tree.nodes.new("GeometryNodeInputIndex")
    index.location = (-1300, -200)

    n_points = image.size[0]
    u_offset = _gn_math(tree, "ADD", 0.5, index.outputs["Index"])
    u_offset.location = (-1100, -180)
    u_norm = _gn_math(tree, "DIVIDE", float(n_points), u_offset.outputs[0])
    u_norm.location = (-950, -180)

    scene_time = tree.nodes.new("GeometryNodeInputSceneTime")
    scene_time.location = (-1300, -340)
    frame_index = _gn_math(
        tree, "SUBTRACT", float(frame_start), scene_time.outputs["Frame"]
    )
    frame_index.location = (-1100, -340)
    v_offset = _gn_math(tree, "ADD", 0.5, frame_index.outputs[0])
    v_offset.location = (-950, -340)
    v_norm = _gn_math(tree, "DIVIDE", float(n_frames), v_offset.outputs[0])
    v_norm.location = (-800, -340)

    combine = tree.nodes.new("ShaderNodeCombineXYZ")
    combine.location = (-650, -260)
    tree.links.new(u_norm.outputs[0], combine.inputs[0])
    tree.links.new(v_norm.outputs[0], combine.inputs[1])
    combine.inputs[2].default_value = 0.0

    img_node = tree.nodes.new("GeometryNodeImageTexture")
    img_node.location = (-450, -260)
    img_node.interpolation = "Closest"
    img_node.inputs["Image"].default_value = image
    tree.links.new(combine.outputs[0], img_node.inputs["Vector"])
    return img_node.outputs["Color"]


def _gn_math(
    tree: bpy.types.NodeTree,
    operation: str,
    const: float,
    socket: bpy.types.NodeSocket,
) -> bpy.types.Node:
    """Build a Math node computing ``socket {op} const``.

    Returns
    -------
    bpy.types.Node
        The new ``ShaderNodeMath`` with ``socket`` wired into input 0.

    """
    node = tree.nodes.new("ShaderNodeMath")
    node.operation = operation
    node.inputs[1].default_value = const
    tree.links.new(socket, node.inputs[0])
    return node
